"use client";

import { useEffect, useLayoutEffect, useMemo, useRef, useState } from "react";
import { Canvas, useFrame, useThree } from "@react-three/fiber";
import { Line } from "@react-three/drei";
import * as THREE from "three";

const R = 1;
const MINT = new THREE.Color("#7ad19c");
const GOLD = new THREE.Color("#f2c94c");
const DEEP = new THREE.Color("#2f6b48");
/** Great-circle radius (degrees) around the active city that lights up gold */
const LIT_DEG = 9;

function toVec(lat: number, lng: number, r = R) {
  const phi = THREE.MathUtils.degToRad(90 - lat);
  const theta = THREE.MathUtils.degToRad(lng + 180);
  return new THREE.Vector3(-r * Math.sin(phi) * Math.cos(theta), r * Math.cos(phi), r * Math.sin(phi) * Math.sin(theta));
}

/** Fibonacci lattice on a sphere: `count` evenly spread points. */
function lattice(count: number, radius: number) {
  const pos = new Float32Array(count * 3);
  const golden = Math.PI * (3 - Math.sqrt(5));
  for (let i = 0; i < count; i++) {
    const y = 1 - (i / (count - 1)) * 2;
    const r = Math.sqrt(1 - y * y);
    const t = golden * i;
    pos.set([Math.cos(t) * r * radius, y * radius, Math.sin(t) * r * radius], i * 3);
  }
  return pos;
}

function geometryOf(pos: Float32Array) {
  const g = new THREE.BufferGeometry();
  g.setAttribute("position", new THREE.BufferAttribute(pos, 3));
  return g;
}

/**
 * Continents as a dot matrix. The dots come from /data/land-dots.bin (Int16 lat*100, lng*100 pairs,
 * generated by scripts/land-dots.mjs from the Natural Earth 50m land shapes).
 */
function useLand() {
  const [land, setLand] = useState<{ vecs: THREE.Vector3[] } | null>(null);
  useEffect(() => {
    let on = true;
    fetch("/data/land-dots.bin")
      .then((r) => r.arrayBuffer())
      .then((buf) => {
        if (!on) return;
        const raw = new Int16Array(buf);
        const n = raw.length / 2;
        const vecs: THREE.Vector3[] = new Array(n);
        for (let i = 0; i < n; i++) vecs[i] = toVec(raw[i * 2] / 100, raw[i * 2 + 1] / 100, R * 1.002);
        setLand({ vecs });
      })
      .catch(() => {});
    return () => {
      on = false;
    };
  }, []);
  return land;
}

const atmosphereShader = {
  vertexShader: /* glsl */ `
    varying vec3 vNormal;
    void main() {
      vNormal = normalize(normalMatrix * normal);
      gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);
    }`,
  fragmentShader: /* glsl */ `
    varying vec3 vNormal;
    void main() {
      float i = pow(0.66 - dot(vNormal, vec3(0.0, 0.0, 1.0)), 2.6);
      gl_FragColor = vec4(0.48, 0.82, 0.61, 1.0) * i * 0.9;
    }`,
};

/** Soft rim light on the globe itself so the sphere reads as a lit ball, not a flat disc */
const rimShader = {
  vertexShader: /* glsl */ `
    varying vec3 vNormal;
    void main() {
      vNormal = normalize(normalMatrix * normal);
      gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);
    }`,
  fragmentShader: /* glsl */ `
    varying vec3 vNormal;
    void main() {
      float f = dot(vNormal, vec3(0.0, 0.0, 1.0));
      float rim = pow(1.0 - clamp(f, 0.0, 1.0), 2.2) * 0.55;
      vec3 base = vec3(0.035, 0.085, 0.06);
      vec3 col = mix(base, vec3(0.3, 0.6, 0.42), rim);
      gl_FragColor = vec4(col, 1.0);
    }`,
};

function arcCurve(from: THREE.Vector3, to: THREE.Vector3) {
  const mid = from.clone().add(to).multiplyScalar(0.5);
  const lift = 1 + from.distanceTo(to) * 0.38;
  mid.normalize().multiplyScalar(R * lift);
  return new THREE.QuadraticBezierCurve3(from, mid, to);
}

function Arc({ curve, active }: { curve: THREE.QuadraticBezierCurve3; active: boolean }) {
  const ref = useRef<{ material: { dashOffset: number } } | null>(null);
  const points = useMemo(() => curve.getPoints(72), [curve]);
  useFrame((_, dt) => {
    if (ref.current) ref.current.material.dashOffset -= dt * (active ? 0.5 : 0.2);
  });
  return (
    <Line
      ref={ref as never}
      points={points}
      color={active ? GOLD : MINT}
      lineWidth={active ? 2.4 : 1.1}
      transparent
      opacity={active ? 1 : 0.42}
      dashed
      dashSize={0.045}
      gapSize={0.028}
    />
  );
}

/** A small gold plane that flies a leg, nose first, over and over */
function Flyer({ curve, speed = 0.18, offset = 0 }: { curve: THREE.QuadraticBezierCurve3; speed?: number; offset?: number }) {
  const ref = useRef<THREE.Group>(null);
  const tmp = useMemo(() => ({ p: new THREE.Vector3(), t: new THREE.Vector3(), a: new THREE.Vector3(), m: new THREE.Matrix4(), up: new THREE.Vector3() }), []);
  useFrame(({ clock }) => {
    const g = ref.current;
    if (!g) return;
    const u = (clock.elapsedTime * speed + offset) % 1;
    curve.getPointAt(u, tmp.p);
    curve.getTangentAt(u, tmp.t);
    tmp.up.copy(tmp.p).normalize();
    tmp.a.copy(tmp.p).add(tmp.t);
    g.position.copy(tmp.p);
    tmp.m.lookAt(tmp.p, tmp.a, tmp.up);
    g.quaternion.setFromRotationMatrix(tmp.m);
  });
  return (
    <group ref={ref}>
      {/* lookAt points -z at the target; the cone points +y by default, so tip it to face -z */}
      <mesh rotation-x={-Math.PI / 2}>
        <coneGeometry args={[0.014, 0.05, 10]} />
        <meshBasicMaterial color={GOLD} />
      </mesh>
      <mesh position-z={0.012}>
        <boxGeometry args={[0.05, 0.004, 0.012]} />
        <meshBasicMaterial color={GOLD} />
      </mesh>
      <sprite scale={[0.12, 0.12, 1]}>
        <spriteMaterial color={GOLD} transparent opacity={0.35} blending={THREE.AdditiveBlending} depthWrite={false} />
      </sprite>
    </group>
  );
}

function Marker({ pos, active }: { pos: THREE.Vector3; active: boolean }) {
  const ring = useRef<THREE.Mesh>(null);
  const ring2 = useRef<THREE.Mesh>(null);
  const beam = useRef<THREE.Mesh>(null);
  const quat = useMemo(() => new THREE.Quaternion().setFromUnitVectors(new THREE.Vector3(0, 0, 1), pos.clone().normalize()), [pos]);

  useFrame(({ clock }) => {
    const pulse = (r: THREE.Mesh | null, phase: number, max: number) => {
      if (!r) return;
      const t = (clock.elapsedTime * 0.7 + phase) % 1;
      r.scale.setScalar(1 + t * max);
      (r.material as THREE.MeshBasicMaterial).opacity = 0.9 * (1 - t);
    };
    pulse(ring.current, 0, active ? 4 : 2.2);
    pulse(ring2.current, 0.5, active ? 4 : 2.2);
    if (beam.current) (beam.current.material as THREE.MeshBasicMaterial).opacity = 0.55 + Math.sin(clock.elapsedTime * 3) * 0.2;
  });

  const c = active ? GOLD : MINT;
  return (
    <group position={pos} quaternion={quat}>
      <mesh>
        <circleGeometry args={[active ? 0.03 : 0.017, 24]} />
        <meshBasicMaterial color={c} side={THREE.DoubleSide} />
      </mesh>
      <mesh ref={ring} position-z={0.001}>
        <ringGeometry args={[0.022, 0.03, 32]} />
        <meshBasicMaterial color={c} transparent side={THREE.DoubleSide} />
      </mesh>
      <mesh ref={ring2} position-z={0.0015}>
        <ringGeometry args={[0.022, 0.03, 32]} />
        <meshBasicMaterial color={c} transparent side={THREE.DoubleSide} />
      </mesh>
      {active && (
        <mesh ref={beam} position-z={0.16} rotation-x={Math.PI / 2}>
          <cylinderGeometry args={[0.004, 0.02, 0.32, 12, 1, true]} />
          <meshBasicMaterial color={GOLD} transparent opacity={0.6} blending={THREE.AdditiveBlending} depthWrite={false} side={THREE.DoubleSide} />
        </mesh>
      )}
    </group>
  );
}

function Stars() {
  const geo = useMemo(() => {
    const n = 900;
    const pos = new Float32Array(n * 3);
    const v = new THREE.Vector3();
    for (let i = 0; i < n; i++) {
      v.randomDirection().multiplyScalar(7 + Math.random() * 3);
      pos.set([v.x, v.y, v.z], i * 3);
    }
    return geometryOf(pos);
  }, []);
  const ref = useRef<THREE.Points>(null);
  useFrame((_, dt) => {
    if (ref.current) ref.current.rotation.y += dt * 0.008;
  });
  return (
    <points ref={ref} geometry={geo}>
      <pointsMaterial color="#cfe8d8" size={0.035} sizeAttenuation transparent opacity={0.5} depthWrite={false} />
    </points>
  );
}

type LabelRefs = React.RefObject<(HTMLButtonElement | null)[]>;

function Globe({ points, active, labelRefs }: { points: [number, number][]; active: number; labelRefs: LabelRefs }) {
  const group = useRef<THREE.Group>(null);
  const land = useLand();
  const ocean = useMemo(() => geometryOf(lattice(1800, R * 1.001)), []);
  const vecs = useMemo(() => points.map(([la, ln]) => toVec(la, ln, R * 1.004)), [points]);
  const curves = useMemo(() => vecs.slice(0, -1).map((v, i) => arcCurve(v, vecs[i + 1])), [vecs]);
  const pointer = useRef(new THREE.Vector2());
  const tmp = useMemo(() => new THREE.Vector3(), []);

  // land dots split into "lit" (around the active city) and the rest
  const { landGeo, litGeo } = useMemo(() => {
    if (!land) return { landGeo: null, litGeo: null };
    const centre = vecs[active].clone().normalize();
    const cos = Math.cos(THREE.MathUtils.degToRad(LIT_DEG));
    const rest: number[] = [];
    const lit: number[] = [];
    const n = new THREE.Vector3();
    land.vecs.forEach((v) => {
      const d = n.copy(v).normalize().dot(centre);
      (d > cos ? lit : rest).push(v.x, v.y, v.z);
    });
    return { landGeo: geometryOf(new Float32Array(rest)), litGeo: geometryOf(new Float32Array(lit)) };
  }, [land, vecs, active]);

  useEffect(() => {
    const onMove = (e: PointerEvent) => pointer.current.set((e.clientX / window.innerWidth) * 2 - 1, (e.clientY / window.innerHeight) * 2 - 1);
    window.addEventListener("pointermove", onMove, { passive: true });
    return () => window.removeEventListener("pointermove", onMove);
  }, []);

  useFrame(({ clock, camera, size }) => {
    const g = group.current;
    if (!g) return;
    // ease the active country round to face the camera, a touch up and left of centre
    const v = vecs[active];
    const targetY = -Math.atan2(v.x, v.z) - 0.18;
    const targetX = THREE.MathUtils.degToRad(points[active][0]) * 0.8 + 0.12;
    let dy = targetY - g.rotation.y;
    dy = Math.atan2(Math.sin(dy), Math.cos(dy)); // shortest way round
    const sway = Math.sin(clock.elapsedTime * 0.35) * 0.05;
    g.rotation.y += (dy + sway + pointer.current.x * 0.14) * 0.05;
    g.rotation.x += (targetX + pointer.current.y * 0.1 - g.rotation.x) * 0.05;
    g.updateMatrixWorld();

    // place the DOM labels over their markers; fade those on the far side
    vecs.forEach((p, i) => {
      const el = labelRefs.current?.[i];
      if (!el) return;
      tmp.copy(p).applyMatrix4(g.matrixWorld);
      const facing = THREE.MathUtils.clamp((tmp.z - 0.1) * 3, 0, 1);
      tmp.project(camera);
      const x = (tmp.x * 0.5 + 0.5) * size.width;
      const y = (-tmp.y * 0.5 + 0.5) * size.height;
      el.style.transform = `translate(-50%, -100%) translate(${x.toFixed(1)}px, ${(y - (i === active ? 22 : 14)).toFixed(1)}px)`;
      el.style.opacity = facing.toFixed(2);
      el.style.pointerEvents = facing > 0.4 ? "auto" : "none";
      el.style.zIndex = String(Math.round(facing * 10) + (i === active ? 10 : 0));
    });
  });

  return (
    <group ref={group} rotation-order="XYZ">
      <mesh>
        <sphereGeometry args={[R * 0.992, 64, 64]} />
        <shaderMaterial {...rimShader} />
      </mesh>
      {/* faint ocean lattice for depth */}
      <points geometry={ocean}>
        <pointsMaterial color={DEEP} size={0.007} sizeAttenuation transparent opacity={0.35} depthWrite={false} />
      </points>
      {/* continents */}
      {landGeo && (
        <points geometry={landGeo}>
          <pointsMaterial color={MINT} size={0.0135} sizeAttenuation transparent opacity={0.95} depthWrite={false} />
        </points>
      )}
      {litGeo && (
        <points geometry={litGeo}>
          <pointsMaterial color={GOLD} size={0.02} sizeAttenuation transparent opacity={1} depthWrite={false} />
        </points>
      )}
      {curves.map((c, i) => (
        <Arc key={i} curve={c} active={i === active || i + 1 === active} />
      ))}
      {/* planes on the legs into and out of the active stop */}
      {curves[active - 1] && <Flyer curve={curves[active - 1]} offset={0.5} />}
      {curves[active] && <Flyer curve={curves[active]} />}
      {vecs.map((v, i) => (
        <Marker key={i} pos={v} active={i === active} />
      ))}
    </group>
  );
}

/** Pulls the camera back so the globe (plus glow) always fits the panel's narrower side. */
function Fit({ radius = 1.14 }: { radius?: number }) {
  const { camera, size } = useThree();
  useLayoutEffect(() => {
    const cam = camera as THREE.PerspectiveCamera;
    const aspect = size.width / size.height;
    const tanHalf = Math.tan(THREE.MathUtils.degToRad(cam.fov / 2)) * Math.min(1, aspect);
    cam.position.set(0, 0, radius / Math.sin(Math.atan(tanHalf)));
    cam.updateProjectionMatrix();
  }, [camera, size, radius]);
  return null;
}

export default function RouteGlobe({
  points,
  labels,
  active,
  onSelect,
  running,
}: {
  points: [number, number][];
  labels: string[];
  active: number;
  onSelect: (i: number) => void;
  running: boolean;
}) {
  const labelRefs = useRef<(HTMLButtonElement | null)[]>([]);

  return (
    <div className="relative size-full">
      <Canvas camera={{ position: [0, 0, 3.1], fov: 38 }} dpr={[1, 2]} frameloop={running ? "always" : "never"} gl={{ antialias: true, alpha: true }}>
        <Fit />
        <Stars />
        <Globe points={points} active={active} labelRefs={labelRefs} />
        <mesh scale={1.2}>
          <sphereGeometry args={[R, 64, 64]} />
          <shaderMaterial {...atmosphereShader} blending={THREE.AdditiveBlending} side={THREE.BackSide} transparent depthWrite={false} />
        </mesh>
      </Canvas>
      {/* DOM labels, positioned every frame by <Globe> */}
      <div className="pointer-events-none absolute inset-0 overflow-hidden">
        {labels.map((label, i) => {
          const on = i === active;
          return (
            <button
              key={label}
              ref={(el) => {
                labelRefs.current[i] = el;
              }}
              type="button"
              onClick={() => onSelect(i)}
              style={{ opacity: 0 }}
              className={
                "absolute left-0 top-0 whitespace-nowrap rounded-sm font-mono uppercase transition-colors duration-300 will-change-transform " +
                (on
                  ? "border border-mint/40 bg-deep px-3.5 py-1.5 text-[13px] font-bold tracking-[0.16em] text-snow shadow-[0_0_0_4px_rgba(122,209,156,.18),0_10px_30px_rgba(30,77,51,.6)]"
                  : "border border-snow/25 bg-transparent px-2.5 py-1 text-[11px] tracking-[0.14em] text-snow/85 hover:border-mint hover:text-mint")
              }
            >
              {label}
            </button>
          );
        })}
      </div>
    </div>
  );
}
